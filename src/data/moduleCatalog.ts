export const moduleCatalog: ModuleSource[] = indexedModules.map(module => {
  const index = module.id === 'opera-night-preview' ? 0 : module.id === 'desire-agent-preview' ? 1 : -1;
  return index < 0 ? module : {
    ...module,
    background: { ...module.background, ...streetBackgrounds[index], sourceRefs: streetModules[index].background.sourceRefs },
    scenes: [...module.scenes.map(scene=>({ ...scene,
      ...(scene.phase==='intro' ? {
        nextSceneIds:streetModules[index].scenes[0].nextSceneIds?.map(id=>`${module.id}-${id}`),
        pageRefs:streetModules[index].scenes[0].pageRefs,
      } : {}),
      starterPrompt: scene.phase==='intro' ? streetBackgrounds[index].openingHook : '这是旧版概括性阶段。请以原文确认进入条件与判定后果，不自动提高热度、发放报酬或生成秘密；精确定位可使用原文场景索引。',
    })), ...streetModules[index].scenes.map(scene => ({
      ...scene, id: `${module.id}-${scene.id}`, moduleId: module.id,
      nextSceneIds: scene.nextSceneIds?.map(id=>`${module.id}-${id}`),
    }))],
  };
});

